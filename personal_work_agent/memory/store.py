"""PostgreSQL storage. Shares Django default database, including transaction settings."""
from contextlib import contextmanager
from datetime import datetime, timezone
from django.db import connection, transaction

class Result:
    def __init__(self, cursor):
        self.rows = cursor.fetchall() if cursor.description else []
        self.rowcount = cursor.rowcount
        self.lastrowid = self.rows[0][0] if self.rows else None
    def fetchone(self):
        return self.rows[0] if self.rows else None
    def fetchall(self):
        return self.rows

class SQLSession:
    def execute(self, sql, params=()):
        # All SQL statements in this module and dashboard views use SQLite-style ?.
        # Replace only placeholders; no dynamic user-provided SQL is accepted.
        sql = sql.replace('?', '%s')
        with connection.cursor() as cursor:
            cursor.execute(sql, params)
            return Result(cursor)

@contextmanager
def connect():
    with transaction.atomic():
        yield SQLSession()

def initialize():
    with connect() as db:
        db.execute('CREATE TABLE IF NOT EXISTS memories (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, content TEXT NOT NULL, created TEXT NOT NULL)')
        db.execute("CREATE TABLE IF NOT EXISTS tasks (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'todo', created TEXT NOT NULL)")

def remember(content: str) -> str:
    with connect() as db:
        db.execute('INSERT INTO memories(content,created) VALUES(?,?)', (content, datetime.now(timezone.utc).isoformat()))
    return 'Đã ghi nhớ thông tin.'

def search_memory(keyword: str) -> str:
    with connect() as db:
        rows = db.execute('SELECT content FROM memories WHERE content ILIKE ? ORDER BY id DESC LIMIT 10', ('%' + keyword + '%',)).fetchall()
    return '\n'.join(row[0] for row in rows) or 'Không có kết quả.'

def add_task(title: str) -> str:
    with connect() as db:
        row = db.execute('INSERT INTO tasks(title,created) VALUES(?,?) RETURNING id', (title, datetime.now(timezone.utc).isoformat()))
        task_id = row.lastrowid
    return f'Đã thêm công việc #{task_id}: {title}'

def list_tasks(status: str = 'all') -> str:
    with connect() as db:
        if status == 'all': rows = db.execute('SELECT id,title,status FROM tasks ORDER BY id DESC LIMIT 100').fetchall()
        else: rows = db.execute('SELECT id,title,status FROM tasks WHERE status=? ORDER BY id DESC LIMIT 100', (status,)).fetchall()
    return '\n'.join(f'#{i} [{s}] {t}' for i,t,s in rows) or 'Không có công việc.'

def complete_task(task_id: int) -> str:
    with connect() as db:
        result = db.execute("UPDATE tasks SET status='done' WHERE id=?", (task_id,))
        return 'Đã hoàn thành.' if result.rowcount else 'Không tìm thấy công việc.'
